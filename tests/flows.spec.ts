import { expect, test, type Page } from '@playwright/test'

async function reachReview(page: Page) {
  await page.clock.install({ time: new Date('2030-06-03T06:00:00Z') })
  await page.goto('/book?service=signature-facial')
  await expect(page.getByLabel('Behandlung auswählen')).toHaveValue('signature-facial')
  const next = page.getByRole('button', { name: 'Weiter', exact: true })
  await next.click()
  await expect(page.getByRole('radio').first()).toBeVisible()
  await next.click()
  await expect(page.getByRole('group', { name: 'Kalendertage' })).toBeVisible()
  await next.click()
  await expect(page.getByText('Bitte wähle ein Datum aus.', { exact: true })).toBeVisible()
  await page.locator('.booking-calendar-day:not(:disabled)').first().click()
  await page.getByRole('group', { name: 'Uhrzeit auswählen' }).getByRole('button').first().click()
  await next.click()
  await expect(page.getByLabel('Vorname')).toBeVisible()
  await next.click()
  await expect(page.getByLabel('Vorname')).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Vorname').fill('Demo')
  await page.getByLabel('Nachname').fill('Test')
  await page.getByLabel('E-Mail-Adresse').fill('demo@example.invalid')
  await page.getByRole('checkbox').check()
  await next.click()
  await expect(page.getByRole('button', { name: 'Terminanfrage senden' })).toBeVisible()
}

test('booking validates required fields and confirms locally without network writes', async ({ page }) => {
  const writes: string[] = []
  page.on('request', request => {
    if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method())) writes.push(request.url())
  })
  await reachReview(page)
  await page.getByRole('button', { name: 'Terminanfrage senden' }).click()
  await expect(page.getByRole('heading', { name: /Danke für deinen/ })).toBeVisible()
  expect(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length }))).toEqual({ local: 0, session: 0 })
  expect(writes).toEqual([])
})

test('an expired slot must be selected again before confirmation', async ({ page }) => {
  await reachReview(page)
  await page.clock.setSystemTime(new Date('2030-06-04T06:00:00Z'))
  await page.getByRole('button', { name: 'Terminanfrage senden' }).click()
  await expect(page.getByText('Bitte wähle einen aktuell verfügbaren Demo-Termin aus.')).toBeVisible()
  await expect(page.getByRole('heading', { name: /Danke für deinen/ })).toHaveCount(0)
  await page.locator('.booking-calendar-day:not(:disabled)').first().click()
  await page.getByRole('group', { name: 'Uhrzeit auswählen' }).getByRole('button').first().click()
  await page.getByRole('button', { name: 'Weiter', exact: true }).click()
  await expect(page.getByLabel('Vorname')).toHaveValue('Demo')
  await page.getByRole('button', { name: 'Weiter', exact: true }).click()
  await page.getByRole('button', { name: 'Terminanfrage senden' }).click()
  await expect(page.getByRole('heading', { name: /Danke für deinen/ })).toBeVisible()
})

test('cart quantity, removal, keyboard close and reload remain local', async ({ page }) => {
  await page.goto('/collection')
  await page.locator('a[href^="/collection/"]').first().click()
  const add = page.getByRole('button', { name: 'In den Warenkorb' })
  await add.click()
  const drawer = page.getByRole('dialog')
  await expect(drawer).toBeVisible()
  await expect(drawer.locator('.cart-quantity span')).toHaveText('1')
  const initial = await drawer.locator('.cart-subtotal strong').innerText()
  await drawer.getByRole('button', { name: /Menge erhöhen/ }).click()
  await expect(drawer.locator('.cart-quantity span')).toHaveText('2')
  const euros = (value: string) => Number(value.replace(/[^\d,]/g, '').replace(',', '.'))
  expect(euros(await drawer.locator('.cart-subtotal strong').innerText())).toBe(euros(initial) * 2)
  await page.keyboard.press('Escape')
  await expect(drawer).toHaveCount(0)
  await expect(add).toBeFocused()
  await page.getByRole('button', { name: /Warenkorb öffnen/ }).click()
  await drawer.getByRole('button', { name: /entfernen$/ }).click()
  await expect(drawer.getByRole('heading', { name: 'Ein Ritual für dich wartet.' })).toBeVisible()
  await page.keyboard.press('Escape')
  await add.click()
  await page.reload()
  await page.getByRole('button', { name: /Warenkorb öffnen, 0 Artikel/ }).click()
  await expect(drawer.getByRole('heading', { name: 'Ein Ritual für dich wartet.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('contact validates inputs and clears them after the demo confirmation', async ({ page }) => {
  await page.goto('/contact')
  await page.getByRole('button', { name: 'Nachricht senden' }).click()
  await expect(page.locator('#contact-name')).toHaveAttribute('aria-invalid', 'true')
  await page.locator('#contact-name').fill('Demo Test')
  await page.locator('#contact-email').fill('demo@example.invalid')
  await page.locator('#contact-subject').fill('Testanfrage')
  await page.locator('#contact-message').fill('Eine unverbindliche Demo-Nachricht.')
  await page.getByRole('button', { name: 'Nachricht senden' }).click()
  await expect(page.getByRole('status')).toContainText('Danke für deine Nachricht.')
  await page.getByRole('button', { name: 'Weitere Demo-Nachricht verfassen' }).click()
  for (const id of ['name', 'email', 'subject', 'message']) await expect(page.locator(`#contact-${id}`)).toHaveValue('')
})
